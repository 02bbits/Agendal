// Generates src/copy/catalog.ts from docs/01-product/copy-catalog.md (the source of truth).
// Run: npm run gen:copy. tests/ui/copy.test.ts fails when the two drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const docPath = fileURLToPath(
  new URL("../../docs/01-product/copy-catalog.md", import.meta.url),
);
const outPath = fileURLToPath(
  new URL("../src/ui/copy/catalog.ts", import.meta.url),
);

export function buildCatalog(markdown) {
  const entries = [];
  for (const line of markdown.split(/\r?\n/)) {
    const match = line.match(
      /^\|\s*`([a-z_]+\.[a-z0-9_]+)`\s*(?:†\s*)?\|\s*(.*?)\s*\|/,
    );
    if (match) entries.push([match[1], match[2]]);
  }
  return entries;
}

export function render(entries) {
  const body = entries
    .map(([key, text]) => `  ${JSON.stringify(key)}: ${JSON.stringify(text)},`)
    .join("\n");
  return `// Generated by scripts/gen-copy.mjs from docs/01-product/copy-catalog.md. Do not edit by hand.\n\nexport const catalog = {\n${body}\n} as const;\n\nexport type CatalogKey = keyof typeof catalog;\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(outPath, render(buildCatalog(readFileSync(docPath, "utf8"))));
  console.log(`wrote ${outPath}`);
}
